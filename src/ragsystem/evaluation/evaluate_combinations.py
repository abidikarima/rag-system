"""
Compare retrieval signals on the evaluation questions.

Signals (each one scores every chunk of the collection against the query):

    dense_text       Qwen3 embedding of the chunk text      (stored in Chroma)
    sparse_text      SPLADE vector of the chunk text        (metadata "sparse_embedding")
    dense_summary    Qwen3 embedding of the chunk summary   (computed here, cached)
    sparse_summary   SPLADE vector of the chunk summary     (metadata "summary_sparse_embedding")

Methods combine one or more signals with one of three fusions:

    score       each signal's scores are min-max normalized over the
                collection, then averaged with the given weights
    agreement   "common chunks first": chunks found in the top
                AGREEMENT_TOP_N of several signals come first (more
                signals = higher), ties are ordered by the score fusion
    rrf         reciprocal rank fusion: sum of 1 / (RRF_K + rank)

Metrics, for k in TOP_KS:

    chunk@k   the expected chunk id is in the top k       (main metric)
    doc@k     a chunk from the expected file is in top k  (same as evaluate_retriver.py)

Run from the repository root:

    uv run python -m ragsystem.evaluation.evaluate_combinations
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import chromadb
import numpy as np
from scipy.sparse import csr_matrix

from ragsystem.core.rag_pipeline.vectorizer import (
    DoclingChunkEmbedder,
    SpladeEmbedder,
)


# Generated by ragsystem.utils.generate_test_questions (see docs/test_data.md).

# TEST_DATA_FILE = Path("./test_data/claude_test_questions.jsonl")
TEST_DATA_FILE = Path("./test_data/groq_test_questions.jsonl")

# Evaluation results are kept apart from the test data. By default the file
# is named after the test set: results/combination_evaluation_<test file>.json
RESULTS_DIR = Path("./results")


CHROMA_DIR = "./chroma_db_v1"
COLLECTION_NAME = "documents"

DENSE_MODEL_NAME = "Qwen/Qwen3-Embedding-0.6B"
SPARSE_MODEL_NAME = "naver/splade-cocondenser-selfdistil"

SPARSE_EMBEDDING_KEY = "sparse_embedding"
SUMMARY_SPARSE_EMBEDDING_KEY = "summary_sparse_embedding"

# Dense summary embeddings are not stored in Chroma: they are computed
# once and cached here (reused while the summary text is unchanged).
SUMMARY_DENSE_CACHE = Path("./.cache/summary_dense_embeddings.npz")

TOP_KS = (5, 10)

# "agreement" fusion: a signal votes for the chunks in its own top N.
AGREEMENT_TOP_N = 10

# "rrf" fusion constant (60 is the usual value).
RRF_K = 60

TEXT_PAIR = {"dense_text": 0.5, "sparse_text": 0.5}
ALL_FOUR = {
    "dense_text": 0.25,
    "sparse_text": 0.25,
    "dense_summary": 0.25,
    "sparse_summary": 0.25,
}

# Method name -> {"fusion": score | agreement | rrf, "weights": {signal: weight}}
METHODS: dict[str, dict[str, Any]] = {
    # --- Single signals --------------------------------------------------
    "Embedding only": {"fusion": "score", "weights": {"dense_text": 1.0}},
    "Sparse only": {"fusion": "score", "weights": {"sparse_text": 1.0}},
    "Summary embedding": {"fusion": "score", "weights": {"dense_summary": 1.0}},
    "Summary sparse": {"fusion": "score", "weights": {"sparse_summary": 1.0}},

    # --- Pairs -----------------------------------------------------------
    "Embedding + sparse": {"fusion": "score", "weights": TEXT_PAIR},
    "Summary embedding + sparse": {
        "fusion": "score",
        "weights": {"dense_summary": 0.5, "sparse_summary": 0.5},
    },
    "Embedding + summary embedding": {
        "fusion": "score",
        "weights": {"dense_text": 0.5, "dense_summary": 0.5},
    },
    "Sparse + summary sparse": {
        "fusion": "score",
        "weights": {"sparse_text": 0.5, "sparse_summary": 0.5},
    },
    "Embedding + summary sparse": {
        "fusion": "score",
        "weights": {"dense_text": 0.5, "sparse_summary": 0.5},
    },
    "Sparse + summary embedding": {
        "fusion": "score",
        "weights": {"sparse_text": 0.5, "dense_summary": 0.5},
    },

    # --- Three signals (all four minus one) -------------------------------
    "All but summary sparse": {
        "fusion": "score",
        "weights": {"dense_text": 1 / 3, "sparse_text": 1 / 3, "dense_summary": 1 / 3},
    },
    "All but summary embedding": {
        "fusion": "score",
        "weights": {"dense_text": 1 / 3, "sparse_text": 1 / 3, "sparse_summary": 1 / 3},
    },
    "All but sparse": {
        "fusion": "score",
        "weights": {"dense_text": 1 / 3, "dense_summary": 1 / 3, "sparse_summary": 1 / 3},
    },
    "All but embedding": {
        "fusion": "score",
        "weights": {"sparse_text": 1 / 3, "dense_summary": 1 / 3, "sparse_summary": 1 / 3},
    },

    "All four": {"fusion": "score", "weights": ALL_FOUR},

    # --- Other fusions -----------------------------------------------------
    "Common first: embedding + sparse": {"fusion": "agreement", "weights": TEXT_PAIR},
    "Common first: all four": {"fusion": "agreement", "weights": ALL_FOUR},
    "RRF: embedding + sparse": {"fusion": "rrf", "weights": TEXT_PAIR},
    "RRF: all four": {"fusion": "rrf", "weights": ALL_FOUR},
}

NAME_WIDTH = max(len(name) for name in METHODS) + 2


# =============================================================
# Loading
# =============================================================

def load_test_data(test_file: Path) -> list[dict[str, Any]]:
    """
    Load test examples from JSONL (id, text, metadata, question).
    """

    if not test_file.is_file():
        raise FileNotFoundError(f"Test data file not found: {test_file}")

    with test_file.open("r", encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def load_collection(chroma_dir: str, collection_name: str) -> dict[str, Any]:
    """
    Load every chunk of the collection with its dense embedding.
    """

    collection = chromadb.PersistentClient(path=chroma_dir).get_collection(
        name=collection_name
    )

    data = collection.get(include=["documents", "metadatas", "embeddings"])

    return {
        "ids": data["ids"],
        "documents": data["documents"],
        "metadatas": [metadata or {} for metadata in data["metadatas"]],
        "embeddings": np.asarray(data["embeddings"], dtype=np.float32),
    }


def sparse_matrix(
    vectors: list[dict | None],
    dimension: int,
) -> csr_matrix:
    """
    Stack {"indices", "values"} dicts into a (n, dimension) CSR matrix.

    Missing vectors become empty rows (score 0).
    """

    rows, cols, values = [], [], []

    for row, vector in enumerate(vectors):
        if not vector:
            continue

        rows.extend([row] * len(vector["indices"]))
        cols.extend(vector["indices"])
        values.extend(vector["values"])

    return csr_matrix(
        (values, (rows, cols)),
        shape=(len(vectors), dimension),
        dtype=np.float32,
    )


def stored_sparse_vectors(
    metadatas: list[dict],
    key: str,
) -> list[dict | None]:

    return [
        json.loads(metadata[key]) if metadata.get(key) else None
        for metadata in metadatas
    ]


def summary_dense_embeddings(
    embedder: DoclingChunkEmbedder,
    ids: list[str],
    summaries: list[str],
) -> np.ndarray:
    """
    Dense embeddings of the summaries, reusing the on-disk cache.

    Chunks without a summary get a zero vector (score 0).
    """

    cached: dict[tuple[str, str], np.ndarray] = {}

    if SUMMARY_DENSE_CACHE.is_file():
        cache = np.load(SUMMARY_DENSE_CACHE, allow_pickle=False)

        for chunk_id, summary, vector in zip(
            cache["ids"], cache["summaries"], cache["vectors"]
        ):
            cached[(str(chunk_id), str(summary))] = vector

    dimension = embedder.model.get_sentence_embedding_dimension()
    result = np.zeros((len(ids), dimension), dtype=np.float32)

    to_encode = [
        index
        for index, (chunk_id, summary) in enumerate(zip(ids, summaries))
        if summary and (chunk_id, summary) not in cached
    ]

    print(
        f"Summary dense embeddings: {len(ids) - len(to_encode)} cached, "
        f"{len(to_encode)} to encode."
    )

    if to_encode:
        vectors = embedder.model.encode(
            [summaries[index] for index in to_encode],
            batch_size=embedder.batch_size,
            normalize_embeddings=True,
            show_progress_bar=True,
        )

        for index, vector in zip(to_encode, vectors):
            cached[(ids[index], summaries[index])] = vector

    for index, (chunk_id, summary) in enumerate(zip(ids, summaries)):
        if summary:
            result[index] = cached[(chunk_id, summary)]

    keys = [
        (chunk_id, summary)
        for chunk_id, summary in zip(ids, summaries)
        if summary
    ]

    SUMMARY_DENSE_CACHE.parent.mkdir(parents=True, exist_ok=True)

    np.savez(
        SUMMARY_DENSE_CACHE,
        ids=np.array([chunk_id for chunk_id, _ in keys]),
        summaries=np.array([summary for _, summary in keys]),
        vectors=np.array(
            [cached[key] for key in keys], dtype=np.float32
        ).reshape(len(keys), dimension),
    )

    return result


# =============================================================
# Scoring
# =============================================================

def min_max(scores: np.ndarray) -> np.ndarray:
    """
    Min-max normalize each row (one row per query) to [0, 1].
    """

    low = scores.min(axis=1, keepdims=True)
    high = scores.max(axis=1, keepdims=True)
    span = np.where(high - low > 0, high - low, 1.0)

    return (scores - low) / span


def ranks(scores: np.ndarray) -> np.ndarray:
    """
    Rank of every chunk for every query (1 = best), shape (queries, chunks).
    """

    order = np.argsort(-scores, axis=1)
    result = np.empty_like(order)
    rows = np.arange(scores.shape[0])[:, None]
    result[rows, order] = np.arange(1, scores.shape[1] + 1)

    return result


def score_fusion(
    signals: dict[str, np.ndarray],
    weights: dict[str, float],
) -> np.ndarray:
    """
    Weighted average of normalized signals, shape (queries, chunks).
    """

    if len(weights) == 1:
        # A single signal: raw scores give the same ranking.
        return signals[next(iter(weights))]

    total = sum(weights.values())

    return sum(
        weight * min_max(signals[name])
        for name, weight in weights.items()
    ) / total


def agreement_fusion(
    signals: dict[str, np.ndarray],
    weights: dict[str, float],
) -> np.ndarray:
    """
    Common chunks first: each signal votes for its own top AGREEMENT_TOP_N.

    Chunks with more votes always rank above chunks with fewer votes
    (chunks found by every signal come first); chunks with the same
    number of votes are ordered by the score fusion.
    """

    votes = sum(
        (ranks(signals[name]) <= AGREEMENT_TOP_N).astype(np.float32)
        for name in weights
    )

    # The fused score is in [0, 1]: it can never outweigh one vote.
    return 2.0 * votes + score_fusion(signals, weights)


def rrf_fusion(
    signals: dict[str, np.ndarray],
    weights: dict[str, float],
) -> np.ndarray:
    """
    Reciprocal rank fusion: only the rank in each signal matters.
    """

    return sum(
        weight / (RRF_K + ranks(signals[name]))
        for name, weight in weights.items()
    )


FUSIONS = {
    "score": score_fusion,
    "agreement": agreement_fusion,
    "rrf": rrf_fusion,
}


def combine(
    signals: dict[str, np.ndarray],
    method: dict[str, Any],
) -> np.ndarray:
    return FUSIONS[method["fusion"]](signals, method["weights"])


# =============================================================
# Evaluation
# =============================================================

def select_examples(
    examples: list[dict[str, Any]],
    chunk_text_by_id: dict[str, str],
) -> list[dict[str, Any]]:
    """
    Keep questions whose expected chunk exists in the collection
    with the same text (ids depend on the chunking).
    """

    missing, changed, valid = 0, 0, []

    for example in examples:
        text = chunk_text_by_id.get(example["id"])

        if text is None:
            missing += 1
        elif text.strip() != example["text"].strip():
            changed += 1
        else:
            valid.append(example)

    print(
        f"Questions: {len(examples)} | usable: {len(valid)} | "
        f"chunk not indexed: {missing} | chunk text changed: {changed}"
    )

    return valid


def evaluate(
    scores_by_method: dict[str, np.ndarray],
    examples: list[dict[str, Any]],
    ids: list[str],
    sources: list[str],
) -> dict[str, Any]:

    max_k = max(TOP_KS)
    summary: dict[str, Any] = {}
    details = []

    for name, scores in scores_by_method.items():
        # Full ranking, needed to report the rank of the expected chunk.
        order = np.argsort(-scores, axis=1)

        hits = {f"chunk@{k}": 0 for k in TOP_KS}
        hits.update({f"doc@{k}": 0 for k in TOP_KS})
        reciprocal_ranks = []

        # chunk@k per difficulty level (if the test file has one).
        by_complexity: dict[str, dict[str, int]] = {}

        for row, example in enumerate(examples):
            ranked_ids = [ids[index] for index in order[row]]
            rank = ranked_ids.index(example["id"]) + 1

            reciprocal_ranks.append(1.0 / rank)

            expected_source = example["metadata"]["source"]

            level = by_complexity.setdefault(
                example.get("complexity", "all"),
                {"total": 0, **{f"chunk@{k}": 0 for k in TOP_KS}},
            )
            level["total"] += 1

            for k in TOP_KS:
                if rank <= k:
                    hits[f"chunk@{k}"] += 1
                    level[f"chunk@{k}"] += 1

                if any(
                    sources[index] == expected_source
                    for index in order[row][:k]
                ):
                    hits[f"doc@{k}"] += 1

            details.append(
                {
                    "method": name,
                    "question_id": example["id"],
                    "question": example["question"],
                    "complexity": example.get("complexity"),
                    "expected_rank": rank,
                    "top_ids": ranked_ids[:max_k],
                }
            )

        total = len(examples)

        summary[name] = {
            **{metric: count / total for metric, count in hits.items()},
            "mrr": float(np.mean(reciprocal_ranks)),
            "hits": hits,
            "by_complexity": {
                name: {
                    "total": counts["total"],
                    **{
                        f"chunk@{k}": counts[f"chunk@{k}"] / counts["total"]
                        for k in TOP_KS
                    },
                }
                for name, counts in by_complexity.items()
            },
            "fusion": METHODS[name]["fusion"],
            "weights": METHODS[name]["weights"],
        }

    return {"summary": summary, "details": details}


def print_table(summary: dict[str, Any], total: int) -> None:
    metrics = [f"chunk@{k}" for k in TOP_KS] + [f"doc@{k}" for k in TOP_KS]

    header = f"{'Method':<{NAME_WIDTH}}" + \
        "".join(f"{m:>10}" for m in metrics) + f"{'MRR':>8}"

    print()
    print("=" * len(header))
    print(f"RESULTS ({total} questions)")
    print("=" * len(header))
    print(header)
    print("-" * len(header))

    for name, result in summary.items():
        print(
            f"{name:<{NAME_WIDTH}}"
            + "".join(f"{result[m]:>10.2%}" for m in metrics)
            + f"{result['mrr']:>8.3f}"
        )

    print("=" * len(header))

    found = {
        level
        for result in summary.values()
        for level in result["by_complexity"]
    }
    order = ("easy", "medium", "hard")
    levels = [level for level in order if level in found] + \
        sorted(found - set(order))

    if levels == ["all"]:
        return

    columns = [(level, k) for level in levels for k in TOP_KS]
    header = f"{'chunk@k by difficulty':<{NAME_WIDTH}}" + "".join(
        f"{f'{level}@{k}':>11}" for level, k in columns
    )

    print()
    print(header)
    print("-" * len(header))

    for name, result in summary.items():
        print(
            f"{name:<{NAME_WIDTH}}"
            + "".join(
                f"{result['by_complexity'].get(level, {}).get(f'chunk@{k}', 0):>11.2%}"
                for level, k in columns
            )
        )

    counts = {
        level: next(iter(summary.values()))[
            "by_complexity"].get(level, {}).get("total", 0)
        for level in levels
    }
    print("Questions per level: " +
          ", ".join(f"{l}={c}" for l, c in counts.items()))
    print("=" * len(header))


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Compare dense/sparse, text/summary retrieval."
    )

    parser.add_argument("--chroma-dir", default=CHROMA_DIR)
    parser.add_argument("--collection", default=COLLECTION_NAME)
    parser.add_argument("--test-file", type=Path, default=TEST_DATA_FILE)
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Default: results/combination_evaluation_<test file name>.json",
    )

    args = parser.parse_args()

    if args.output is None:
        args.output = RESULTS_DIR / \
            f"combination_evaluation_{args.test_file.stem}.json"

    return args


def main() -> None:
    args = parse_args()

    # ---------------------------------------------------------
    # 1. Load collection and test questions
    # ---------------------------------------------------------

    data = load_collection(args.chroma_dir, args.collection)

    ids = data["ids"]
    metadatas = data["metadatas"]
    sources = [metadata.get("source") for metadata in metadatas]

    print(
        f"Collection: {len(ids)} chunks from "
        f"{len(set(sources))} files ({args.chroma_dir})"
    )

    examples = select_examples(
        load_test_data(args.test_file),
        dict(zip(ids, data["documents"])),
    )

    if not examples:
        expected = sorted(
            {example["metadata"]["source"]
                for example in load_test_data(args.test_file)}
        )
        raise SystemExit(
            "No usable question: the expected chunks are not in this "
            "collection. Index their file(s) first, e.g.\n"
            f"  uv run python scripts/update_rag_data.py --chroma-dir {args.chroma_dir} "
            f"--skip-download --files {' '.join(expected)}"
        )

    for key in (SPARSE_EMBEDDING_KEY, SUMMARY_SPARSE_EMBEDDING_KEY):
        missing = sum(1 for metadata in metadatas if not metadata.get(key))
        if missing:
            print(f"[WARNING] {missing} chunks have no '{key}' (score 0).")

    # ---------------------------------------------------------
    # 2. Load models and encode queries
    # ---------------------------------------------------------

    dense = DoclingChunkEmbedder(
        model_name=DENSE_MODEL_NAME,
        batch_size=32,
        normalize_embeddings=True,
    )
    splade = SpladeEmbedder(model_name=SPARSE_MODEL_NAME)

    # SPLADE indices are token ids of the tokenizer vocabulary.
    vocabulary_size = len(splade.model.tokenizer)
    questions = [example["question"] for example in examples]

    # Same query encoding as ChromaRetriever ("query" prompt).
    query_dense = np.asarray(
        dense.embed_vectors(questions, prompt_name="query"),
        dtype=np.float32,
    )

    query_sparse = sparse_matrix(
        [splade.embed_query(question) for question in questions],
        vocabulary_size,
    )

    # ---------------------------------------------------------
    # 3. Score every chunk with every signal
    # ---------------------------------------------------------

    summaries = [metadata.get("summary") or "" for metadata in metadatas]

    text_sparse = sparse_matrix(
        stored_sparse_vectors(metadatas, SPARSE_EMBEDDING_KEY),
        vocabulary_size,
    )
    summary_sparse = sparse_matrix(
        stored_sparse_vectors(metadatas, SUMMARY_SPARSE_EMBEDDING_KEY),
        vocabulary_size,
    )
    summary_dense = summary_dense_embeddings(dense, ids, summaries)

    # Dense vectors are L2-normalized: dot product = cosine similarity.
    # Sparse: SPLADE dot product.
    signals = {
        "dense_text": query_dense @ data["embeddings"].T,
        "sparse_text": (query_sparse @ text_sparse.T).toarray(),
        "dense_summary": query_dense @ summary_dense.T,
        "sparse_summary": (query_sparse @ summary_sparse.T).toarray(),
    }

    scores_by_method = {
        name: combine(signals, method)
        for name, method in METHODS.items()
    }

    # ---------------------------------------------------------
    # 4. Evaluate and save
    # ---------------------------------------------------------

    evaluation = evaluate(scores_by_method, examples, ids, sources)

    print_table(evaluation["summary"], len(examples))

    args.output.parent.mkdir(parents=True, exist_ok=True)

    with args.output.open("w", encoding="utf-8") as f:
        json.dump(
            {
                "chroma_dir": args.chroma_dir,
                "collection": args.collection,
                "collection_chunks": len(ids),
                "collection_files": len(set(sources)),
                "questions": len(examples),
                "top_ks": list(TOP_KS),
                **evaluation,
            },
            f,
            indent=2,
            ensure_ascii=False,
        )

    print(f"Detailed results saved to: {args.output}")


if __name__ == "__main__":
    main()
